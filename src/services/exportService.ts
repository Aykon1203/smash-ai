import { Share, Alert, Platform } from 'react-native';
import { ShotAnalysis } from '../types/badminton';

/**
 * Formats a clean, readable text report suitable for sharing with coaches, players, or notes.
 */
export function formatAnalysisReport(analysis: ShotAnalysis): string {
  const goodList = analysis.goodPoints.map((pt, i) => `  ${i + 1}. [GOOD] ${pt}`).join('\n');
  const badList = analysis.badPoints.map((pt, i) => `  ${i + 1}. [WORK ON] ${pt}`).join('\n');
  const coachTips = analysis.coachTips.map((tip, i) => `  • ${tip}`).join('\n');

  return `🏸 SMASHAI BADMINTON SHOT REPORT 🏸
----------------------------------------
Shot Type: ${analysis.shotName} (${analysis.shotCategory})
Technique Score: ${analysis.score}/100
Analysis Time: ${analysis.analyzedAt}
Summary: ${analysis.tagline}

KEY METRICS:
- Estimated Smash Speed: ${analysis.metrics.speedKmh} km/h
- Contact Height: ${analysis.metrics.contactHeightM} m
- Impact Downward Angle: ${analysis.metrics.impactAngleDeg}°
- Kinetic Chain Efficiency: ${analysis.metrics.kineticChainEfficiency}%

GOOD POINTS (STRENGTHS):
${goodList}

AREAS FOR IMPROVEMENT (BAD POINTS):
${badList}

COACH RECOMMENDATIONS & DRILLS:
${coachTips}
----------------------------------------
Generated by SmashAI - AI Badminton Technique Coach`;
}

/**
 * Native export and sharing of the badminton feedback
 */
export async function exportFeedback(analysis: ShotAnalysis): Promise<boolean> {
  try {
    const report = formatAnalysisReport(analysis);
    const result = await Share.share(
      {
        title: `SmashAI Feedback - ${analysis.shotName}`,
        message: report,
      },
      {
        dialogTitle: `Export SmashAI Feedback (${analysis.shotName})`,
        subject: `SmashAI Feedback - ${analysis.shotName}`,
      }
    );

    if (result.action === Share.sharedAction) {
      return true;
    }
    return false;
  } catch (error: any) {
    console.error('Failed to export feedback:', error);
    Alert.alert('Export Feedback', 'Unable to open share sheet. Please try again.');
    return false;
  }
}
